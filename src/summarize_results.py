"""Build results/RESULTS.md from results/*.json so no number is hand-copied.

  python summarize_results.py
"""
import glob
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
TR = {Path(f).stem: json.loads(Path(f).read_text()) for f in glob.glob(str(R / "transformers" / "*.json"))}
LR = json.loads((R / "lr_results.json").read_text())
LEAK = json.loads((R / "leak_check.json").read_text()) if (R / "leak_check.json").exists() else None
MODELS = ["bert-base-uncased", "roberta-base", "bert-large-uncased", "roberta-large"]
DIVERGED = 0.10  # val macro-F1 below this = collapsed to one class
SEEDS = [412, 413, 414]


def cell(m):
    return f"{m['macro_f1']:.3f} ({m['acc']:.3f})"


def tcell(run):
    r = TR.get(run)
    if r is None:
        return "not run"
    s = cell(r)
    return s + " **diverged**" if r["val_macro_f1"] < DIVERGED else s


def best_lr(model):
    rs = [r for k, r in TR.items() if k.startswith(f"{model}_none_official_6way_lr")
          and r["val_macro_f1"] >= DIVERGED]
    return max(rs, key=lambda r: r["val_macro_f1"])["args"]["lr"] if rs else (1e-5 if "large" in model else 2e-5)


def name(model, meta="none", drop="", raw=False, split="official", task="6way", lr=None):
    lr = best_lr(model) if lr is None else lr
    return (f"{model}_{meta}{'-' + drop if drop else ''}{'_rawcredit' if raw else ''}"
            f"_{split}_{task}_lr{lr:g}_s412")


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def main():
    md = ["# Results", "",
          "Generated by `src/summarize_results.py` from `results/*.json`. Do not edit by hand.", "",
          "All numbers are test-set **macro-F1 (accuracy)**, seed 412, one run each (section 4b adds seeds 413 and 414). "
          "With n = 1,283 the 95% CI on accuracy is about ±0.024, so differences under ~0.03 are noise.", ""]

    md += ["## 1. TF-IDF + logistic regression", ""]
    names = {"text": "Text only", "text+meta(raw)": "Text + meta (raw credit)",
             "text+meta(corr)": "Text + meta (corrected credit)", "text+meta(-credit)": "Text + meta (no credit)",
             "meta(corr)": "Meta only (corrected credit)"}
    md.append(table(["Condition", "Official 6-way", "Official binary", "Disjoint 6-way", "Disjoint binary"],
                    [[n] + [cell(LR[f"{s}|{t}|{c}"]) for s in ["official", "disjoint"] for t in ["6way", "binary"]]
                     for c, n in names.items()]))
    md.append("")

    md += ["## 2. Transformers, text only: learning-rate grid (official, 6-way)", "",
           "Validation macro-F1 picks the learning rate. Test macro-F1 (accuracy) shown next to it.", ""]
    rows = []
    for m in MODELS:
        for lr in [1e-5, 2e-5, 3e-5]:
            r = TR.get(name(m, lr=lr))
            if r:
                rows.append([m, f"{lr:g}", f"{r['val_macro_f1']:.3f}", tcell(name(m, lr=lr)),
                             "yes" if lr == best_lr(m) else ""])
    md.append(table(["Model", "LR", "Val F1", "Test", "Picked"], rows))
    md.append("")

    md += ["## 3. Transformers: text vs. metadata (official split)", "",
           "Each model at its picked learning rate. Binary = half-true and above vs. the rest.", "",
           "> **Warning:** the *corrected credit* column on the official split is **not leak-free** for "
           "transformers. See section 6. Read it as an upper bound, not as a clean metadata result.", ""]
    rows = [["TF-IDF + LR"] + [cell(LR[k]) for k in ["official|6way|text", "official|6way|text+meta(corr)",
                                                       "official|6way|text+meta(raw)", "official|binary|text"]]]
    for m in MODELS:
        rows.append([m, tcell(name(m)), tcell(name(m, "all")), tcell(name(m, "all", raw=True)),
                     tcell(name(m, task="binary"))])
    md.append(table(["Model", "6-way text", "6-way text + meta (corrected)", "6-way text + meta (raw)",
                     "Binary text"], rows))
    md.append("")

    md += ["## 4. Speaker-disjoint split (6-way)", "",
           "No speaker appears in more than one split (`data.speaker_disjoint(seed=412)`).", ""]
    m = "roberta-base"
    rows = [["TF-IDF + LR"] + [cell(LR[f"disjoint|6way|{c}"]) for c in ["text", "text+meta(corr)", "text+meta(raw)"]],
            [m, tcell(name(m, split="disjoint")), tcell(name(m, "all", split="disjoint")),
             tcell(name(m, "all", raw=True, split="disjoint"))]]
    md.append(table(["Model", "Text", "Text + meta (corrected)", "Text + meta (raw)"], rows))
    md.append("")

    md += ["## 4b. Main grid over seeds (6-way, corrected credit)", "",
           "Test macro-F1 for each seed, then mean ± sample SD. Same-seed reruns on the same GPU differ by "
           "~0.02 (GPU nondeterminism), so compare means, and use the paired bootstrap before claiming a difference.", ""]
    rows = []
    for mm in MODELS:
        for meta, mlabel in [("none", "text"), ("all", "text + meta")]:
            for split in ["official", "disjoint"]:
                base = name(mm, meta, split=split)[:-len("_s412")]
                ok = {s: TR[f"{base}_s{s}"] for s in SEEDS if f"{base}_s{s}" in TR}
                if not ok:
                    continue
                fs = [r["macro_f1"] for r in ok.values() if r["val_macro_f1"] >= DIVERGED]  # diverged runs left out
                cells = ["not run" if s not in ok else f"{ok[s]['macro_f1']:.3f}"
                         + (" **diverged**" if ok[s]["val_macro_f1"] < DIVERGED else "") for s in SEEDS]
                mean = (f"{statistics.mean(fs):.3f}" + (f" ± {statistics.stdev(fs):.3f}" if len(fs) > 1 else "")
                        if fs else "n/a")
                rows.append([mm, mlabel, split] + cells + [mean])
    md.append(table(["Model", "Input", "Split"] + [f"s{s}" for s in SEEDS] + ["Mean ± SD"], rows))
    md += ["", "> The official-split metadata gain is an upper bound: corrected credit still leaks the label for "
           "seen speakers (section 6). The disjoint split is the clean test of metadata.", ""]

    md += ["## 5. Leave-one-field-out ablation (official, 6-way, corrected credit)", "",
           "Full model minus one metadata field. Same leakage caveat as section 3.", ""]
    a = LR["ablation_official_6way_corr"]
    full_lr = LR["official|6way|text+meta(corr)"]["macro_f1"]
    full_tr = TR.get(name(m, "all"))
    rows = [["(none dropped)", f"{full_lr:.3f}", f"{full_tr['macro_f1']:.3f}" if full_tr else "not run"]]
    for f in ["party", "speaker", "job", "state", "context", "subject", "credit"]:
        r = TR.get(name(m, "all", drop=f))
        rows.append([f"-{f}", f"{a['-' + f]['macro_f1']:.3f}", f"{r['macro_f1']:.3f}" if r else "not run"])
    md.append(table(["Dropped field", "TF-IDF + LR macro-F1", "RoBERTa-base macro-F1"], rows))
    md.append("")

    if LEAK:
        md += ["## 6. Residual credit-history leak (`src/leak_check.py`)", "",
               f"Credit counts are one snapshot per speaker (identical on "
               f"{LEAK['history_constant_within_speaker']:.1%} of multi-row speakers). The correction leaves "
               "`speaker_total - onehot(label)`. Training labels reveal each speaker's total, so for a seen speaker "
               "the gap between total and corrected history spells out the label. A lookup with no learning:", ""]
        md.append(table(["Split", "Test rows resolved", "Accuracy on resolved", "Overall macro-F1 (acc)"],
                        [[s, f"{LEAK[s]['resolved_frac']:.1%}",
                          f"{LEAK[s]['acc_on_resolved']:.3f}" if LEAK[s]["acc_on_resolved"] is not None else "n/a",
                          cell(LEAK[s])] for s in ["official", "disjoint"]]))
        md += ["", "Linear models can't exploit this (they can't do the per-speaker lookup), which is why LR "
               "with corrected credit stays near text-only. Transformers likely learn part of it on the official split, "
               "which would explain the corrected-credit results above raw credit for RoBERTa-large and the large "
               "run-to-run swings in section 5. On the speaker-disjoint split the lookup resolves nothing.", ""]

    failed = [k for k, r in TR.items() if r["val_macro_f1"] < DIVERGED]
    if failed:
        md += ["## Failed runs", ""] + [f"- `{k}`: collapsed to a single class (val macro-F1 "
                                        f"{TR[k]['val_macro_f1']:.3f}). Needs a rerun with another seed or LR." for k in failed]
        md.append("")
    (R / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {R / 'RESULTS.md'} ({len(TR)} transformer runs)")


if __name__ == "__main__":
    main()
